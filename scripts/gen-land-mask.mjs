/**
 * Generates the dotted-land bitmask used by the visitor map.
 *
 * Rasterises Natural Earth's 110m land polygons onto a 1-degree equirectangular
 * grid and writes it out as packed bits. Doing this at build time keeps
 * world-atlas/topojson/d3-geo out of the browser bundle — the runtime only ever
 * sees a ~8KB base64 string.
 *
 *   node scripts/gen-land-mask.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

// Antarctica is cropped the way web maps conventionally crop it: keeping it
// would spend a quarter of the panel on a landmass with no visitors.
const LON_MIN = -180;
const LON_MAX = 180;
const LAT_MAX = 84;
const LAT_MIN = -56;
const STEP = 1; // degrees per grid cell

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

const topology = JSON.parse(
  fs.readFileSync(path.join(root, 'node_modules/world-atlas/land-110m.json'), 'utf8')
);
const land = feature(topology, topology.objects.land);

const cols = Math.round((LON_MAX - LON_MIN) / STEP);
const rows = Math.round((LAT_MAX - LAT_MIN) / STEP);
const bytes = new Uint8Array(Math.ceil((cols * rows) / 8));

let hits = 0;
for (let row = 0; row < rows; row++) {
  // Sample cell centres so coastlines land consistently on one side.
  const lat = LAT_MAX - (row + 0.5) * STEP;
  for (let col = 0; col < cols; col++) {
    const lon = LON_MIN + (col + 0.5) * STEP;
    if (!geoContains(land, [lon, lat])) continue;
    const bit = row * cols + col;
    bytes[bit >> 3] |= 0x80 >> (bit & 7);
    hits++;
  }
}

const base64 = Buffer.from(bytes).toString('base64');
const out = `// Generated by scripts/gen-land-mask.mjs — do not edit by hand.
// ${cols}x${rows} 1-degree equirectangular land grid, packed one bit per cell
// (row-major, MSB first), covering lon [${LON_MIN}, ${LON_MAX}] and lat [${LAT_MIN}, ${LAT_MAX}].

export const LAND_MASK_COLS = ${cols};
export const LAND_MASK_ROWS = ${rows};
export const LAND_LON_MIN = ${LON_MIN};
export const LAND_LON_MAX = ${LON_MAX};
export const LAND_LAT_MIN = ${LAT_MIN};
export const LAND_LAT_MAX = ${LAT_MAX};

export const LAND_MASK_BASE64 =
  '${base64}';

let decoded: Uint8Array | null = null;

/** Decodes the packed mask once and caches it. */
export function getLandMask(): Uint8Array {
  if (decoded) return decoded;
  const binary = atob(LAND_MASK_BASE64);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  decoded = out;
  return out;
}

/** True when the given grid cell is land. */
export function isLand(mask: Uint8Array, col: number, row: number): boolean {
  const bit = row * LAND_MASK_COLS + col;
  return (mask[bit >> 3] & (0x80 >> (bit & 7))) !== 0;
}
`;

const target = path.join(root, 'src/lib/landMask.ts');
fs.writeFileSync(target, out);
console.log(
  `wrote ${path.relative(root, target)}: ${cols}x${rows} grid, ${hits} land cells, ${(base64.length / 1024).toFixed(1)}KB base64`
);
